def choose_direction(recent_prompts):
    """최근 작품에 사용한 축별 선택지를 우선 제외합니다. DB 변경 없이 프롬프트에 보관합니다."""
    recent_text = '\n'.join(recent_prompts)
    choices = []
    for axis, options in AXES.items():
        candidates = [option for option in options if option not in recent_text]
        choices.append(f'{axis}: {secrets.choice(candidates or options)}')
    return '\n'.join(choices)


